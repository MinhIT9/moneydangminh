export const messages: Record<Locale, Record<MessageKey, string>> = { vi, en };

export function translate(locale: Locale, key: MessageKey, values: TranslationValues = {}): string {
  return messages[locale][key].replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = values[name];
    return value === undefined ? match : String(value);
  });
}

